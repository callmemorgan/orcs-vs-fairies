/** Eight directions, with half-sector ties toward increasing signed angle. */
export function facing8(x: number, y: number): number {
  if (y === 0) return x < 0 ? 4 : 0;
  if (x === 0) return y < 0 ? 6 : 2;
  let ax = Math.abs(x), ay = Math.abs(y);
  // Normalize subnormal vectors before the boundary product can underflow.
  const scale = Math.max(ax, ay), boundary = .41421356237309503;
  if (scale < 2.2250738585072014e-308) { ax /= scale; ay /= scale; }
  if (x >= 0 && y >= 0) return ay < ax * boundary ? 0 : ax <= ay * boundary ? 2 : 1;
  if (x < 0 && y >= 0) return ay <= ax * boundary ? 4 : ax < ay * boundary ? 2 : 3;
  if (x < 0 && y < 0) return ay < ax * boundary ? 4 : ax <= ay * boundary ? 6 : 5;
  return ay <= ax * boundary ? 0 : ax < ay * boundary ? 6 : 7;
}

